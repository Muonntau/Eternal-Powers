def canvas(w,h):
    im=Image.new('RGBA',(w,h),(0,0,0,0)); return im,ImageDraw.Draw(im)
def save(im,name,kind='props',anchor=None):
    im.save(OUT / f'{name}.png')
    entry={'src':f'/assets/{name}.png','width':im.width,'height':im.height}
    if anchor:entry['anchor']=anchor
    manifest[kind][name]=entry
def pxellipse(d,box,c):d.ellipse(tuple(map(int,box)),fill=c)
def shadow(d,x,y,rx,ry):
    pxellipse(d,(x-rx,y-ry,x+rx,y+ry),(8,25,24,65))
def flecks(d,w,h,cols,n=100,seed=0):
    r=random.Random(seed)
    for i in range(n):
        x=r.randrange(w);y=r.randrange(h);c=r.choice(cols)
        d.rectangle((x,y,x+r.choice([0,1,2]),y),fill=c)

