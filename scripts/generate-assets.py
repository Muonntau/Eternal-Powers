def recolor(im,colors):
    result=im.copy()
    for y in range(im.height):
        for x in range(im.width):
            r,g,b,a=im.getpixel((x,y))
            if not a:continue
            light=(r*.3+g*.5+b*.2)/255
            lo,hi=colors
            result.putpixel((x,y),(int(lo[0]+(hi[0]-lo[0])*light),int(lo[1]+(hi[1]-lo[1])*light),int(lo[2]+(hi[2]-lo[2])*light),a))
    return result
